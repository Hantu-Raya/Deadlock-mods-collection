"use strict";
// Generates the DLF pickup-ring runtime from the canonical HP Colors Rewrite v2 sources.
//   node dlf/scripts/compose-pickups.js <panorama dir>   (writes scripts/dlf/pickup_*.js there)
// The canonical files are pinned in dlf/pickup-source-pin.json. Every adaptation is an exact
// substitution with an expected match count, so upstream drift fails the build instead of
// silently shipping a half-adapted copy. After reviewing an upstream change, re-pin with
//   node dlf/scripts/compose-pickups.js --pin
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const REPO = path.join(__dirname, "..", "..");
const PIN = path.join(__dirname, "..", "pickup-source-pin.json");
const SOURCES = {
  timer: "hp_colors_rewrite_v2/panorama/scripts/test_topbar_pickups.js",
  bridge: "hp_colors_rewrite_v2/panorama/scripts/test_event_bridge.js",
  contract: "hp_colors_rewrite_v2/panorama/scripts/hp_colors_v2_contract.js"
};
const TAG = "[DLF-PU]";

// DLF message names: an installed HPv2 pak02 can neither feed nor configure DLF's rings.
const SHARED = [
  ["HPV2_PICKUP_SNAPSHOT", "DLF_PICKUP_SNAPSHOT"],
  ["[test_hpv2]", TAG]
];
const EDITS = {
  timer: [
    ...SHARED,
    ["HPV2_PICKUP_SCAN_GATE", "DLF_PICKUP_SCAN_GATE"],
    ["HPV2_ULTIMATE_SNAPSHOT", "DLF_ULTIMATE_SNAPSHOT"],
    ['var CONFIG_MAGIC = "HP_COLORS_V2_CONFIG";', 'var CONFIG_MAGIC = "DLF_PICKUP_CONFIG";', 1],
    ['var CONFIG_ATTR = "hp_colors_v2_config";', 'var CONFIG_ATTR = "dlf_pickup_config";', 1],
    ["$.HPColorsV2ContractFactory", "$.DLFPickupContractFactory", 4],
    // Read-only sampling: never restyle the native world-healthbar pickup icons.
    ["          styleNativePickup(matches[match], bit);\n", "", 1]
  ],
  bridge: [
    ...SHARED,
    ['var relayAttribute = "hpv2_pickup_message";', 'var relayAttribute = "dlf_pickup_message";', 1],
    ['"file://{resources}/layout/test_event_relay.xml"', '"file://{resources}/layout/dlf/pickup_event_relay.xml"', 1]
  ]
};
// HPv2 defaults for everything the timer reads, with the world ultimate overlay off.
const CONFIG_KEYS = ["enabled", "pickupTimersEnabled", "pickupGunColor", "pickupMovementColor", "pickupSpiritColor",
  "pickupSurvivalColor", "pickupBackgroundDarkness", "pickupGlyphColor", "pickupSize", "pickupSpacing",
  "pickupOffsetX", "pickupOffsetY", "ultimateTimerEnabled", "ultimateTimerSize", "ultimateTimerDarkness"];
const DLF_OVERRIDES = { enabled: true, pickupTimersEnabled: true, ultimateTimerEnabled: false };

const sha256 = (text) => crypto.createHash("sha256").update(text).digest("hex");
// Pins, checks and generated headers hash the LF-normalized text, so a CRLF checkout matches its pin.
const sourceHash = (text) => sha256(text.replace(/\r\n/g, "\n"));

function readSources({ checkPin = true } = {}) {
  const pin = checkPin ? JSON.parse(fs.readFileSync(PIN, "utf8")) : {};
  const out = {};
  for (const [key, rel] of Object.entries(SOURCES)) {
    const text = fs.readFileSync(path.join(REPO, rel), "utf8").replace(/\r\n/g, "\n");
    if (checkPin && pin[rel] !== sourceHash(text)) {
      throw new Error(`${rel} changed since dlf/pickup-source-pin.json; review the diff, then run compose-pickups.js --pin`);
    }
    out[key] = text;
  }
  return out;
}

function applyEdits(name, text) {
  for (const [from, to, expected] of EDITS[name]) {
    const count = text.split(from).length - 1;
    if (expected === undefined ? count < 1 : count !== expected) {
      throw new Error(`${name}: expected ${expected === undefined ? "at least 1" : expected} match(es) of ${JSON.stringify(from)}, found ${count}`);
    }
    text = text.split(from).join(to);
  }
  if (/HPV2_PICKUP_SNAPSHOT|HPV2_PICKUP_SCAN_GATE|HPV2_ULTIMATE_SNAPSHOT|HP_COLORS_V2_CONFIG/.test(text)) {
    throw new Error(`${name}: an HPv2 message name survived adaptation`);
  }
  return text;
}

function pickupConfig(contractSource) {
  const $ = {};
  vm.runInNewContext(contractSource, { $, Object, Array, Number, String, Math, JSON, isFinite, parseInt, parseFloat, RegExp });
  const defaults = $.HPColorsV2ContractFactory.create().normalizeValues(null);
  const config = {};
  for (const key of CONFIG_KEYS) {
    if (!(key in defaults)) throw new Error(`contract default missing: ${key}`);
    config[key] = key in DLF_OVERRIDES ? DLF_OVERRIDES[key] : defaults[key];
  }
  return config;
}

function compose() {
  const sources = readSources();
  const config = pickupConfig(sources.contract);
  const header = (rel) => `// Generated by dlf/scripts/compose-pickups.js from ${rel} (sha256 ${sourceHash(sources[Object.keys(SOURCES).find((k) => SOURCES[k] === rel)]).slice(0, 12)}). Do not edit.\n`;
  return {
    "scripts/dlf/pickup_config.js": `// Generated by dlf/scripts/compose-pickups.js from HPv2 contract defaults. Do not edit.\n` +
      `$.DLFPickupConfig = Object.freeze(${JSON.stringify(config, null, 2)});\n` +
      `$.DLFPickupContractFactory = { create: function () { return { normalizeValues: function () { return $.DLFPickupConfig; } }; } };\n`,
    "scripts/dlf/pickup_timers.js": header(SOURCES.timer) + applyEdits("timer", sources.timer),
    "scripts/dlf/pickup_bridge.js": header(SOURCES.bridge) + applyEdits("bridge", sources.bridge)
  };
}

function writeTo(panoramaDir) {
  const files = compose();
  for (const [rel, text] of Object.entries(files)) {
    const out = path.join(panoramaDir, rel);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, text);
  }
  return Object.keys(files);
}

if (require.main === module) {
  const arg = process.argv[2];
  if (arg === "--pin") {
    const pin = {};
    for (const [key, text] of Object.entries(readSources({ checkPin: false }))) pin[SOURCES[key]] = sourceHash(text);
    fs.writeFileSync(PIN, JSON.stringify(pin, null, 2) + "\n");
    compose();
    console.log(`pinned ${Object.keys(pin).length} canonical sources`);
  } else if (arg) {
    for (const rel of writeTo(arg)) console.log(`composed ${rel}`);
  } else {
    console.error("usage: node compose-pickups.js <panorama dir> | --pin");
    process.exit(2);
  }
}

module.exports = { compose, writeTo, sourceHash, SOURCES };
