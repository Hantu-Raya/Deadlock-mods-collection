"""Refresh observer_hud's stock Deadlock files from SteamTracking/GameTracking-Deadlock.

    py observer_hud/scripts/refresh-stock.py            # refresh the stock copies and tables, pin them
    py observer_hud/scripts/refresh-stock.py --check    # exit 1 when upstream moved past the pin
    py observer_hud/scripts/refresh-stock.py --accept   # after a manual rebase: pin the overrides too

`stock/*.xml` are verbatim stock layouts that the validator boots the mod inside; they are refreshed
automatically, and so are the generated tables `panorama/scripts/observer_hud/oh_heroes.js` (ban
picker), `oh_debuff_icons.js` (status column icons) and `oh_item_icons.js` (purchase notice icons). The two overrides
(`hud_spectate_bar.xml`, `citadel_status_effect.xml`) carry this mod's includes on top of stock; for
those the script only reports upstream drift. Rebase them by hand (diff the pinned and current stock
file, port the change), then run --accept.

The table builders are DLF's (dlf/scripts/refresh-stock.py): they describe game data, not DLF.
"""
import hashlib
import importlib.util
import json
import pathlib
import re
import sys

MODULE = pathlib.Path(__file__).resolve().parents[1]
PIN = MODULE / "stock-pin.json"
_spec = importlib.util.spec_from_file_location("dlf_refresh", MODULE.parent / "dlf" / "scripts" / "refresh-stock.py")
dlf = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(dlf)

REPO = dlf.REPO
PANORAMA = dlf.PANORAMA
# Stock path -> verbatim copy (validator fixtures).
STOCK = {PANORAMA + f"layout/{name}.xml": f"stock/{name}.xml" for name in (
    "hud", "hud_escape_menu", "citadel_hud_top_bar", "citadel_hud_top_bar_team", "citadel_hud_top_bar_player",
    "unit_status_overlay_v2", "citadel_hud_hero_shop")}
# Stock path -> this mod's file that carries edits on top of it.
OVERRIDDEN = {
    PANORAMA + "layout/hud_spectate_bar.xml": "panorama/layout/hud_spectate_bar.xml",
    PANORAMA + "layout/citadel_status_effect.xml": "panorama/layout/citadel_status_effect.xml",
}
HEROES_OUT = "panorama/scripts/observer_hud/oh_heroes.js"
ICONS_OUT = "panorama/scripts/observer_hud/oh_debuff_icons.js"
ITEMS_OUT = "panorama/scripts/observer_hud/oh_item_icons.js"


def rename(text, old, new):
    return (text.replace("dlf/scripts/refresh-stock.py", "observer_hud/scripts/refresh-stock.py")
            .replace(f"var {old} =", f"var {new} ="))


def hero_table(*data):
    return rename(dlf.hero_table(*data), "DLF_HEROES", "OH_HEROES")


def icon_table(*data):
    return rename(dlf.icon_table(*data), "DLF_DEBUFF_ICONS", "OH_DEBUFF_ICONS")


def item_table(vdata, names_text):
    """English shop name -> icon path under file://{images}/ without .psd (m_strShopIconLarge, else
    m_strAbilityImage). The shop list's purchase rows carry only the item's display name."""
    images = {}
    for key, body in zip(*[iter(re.split(r"\n\t([a-z0-9_]+) = \n", vdata)[1:])] * 2):
        if not re.search(r'\n\t\tm_eAbilityType = "?EAbilityType_Item"?\n', body):
            continue
        found = (re.search(r'\n\t\tm_strShopIconLarge = panorama:"file://\{images\}/([a-z0-9_./-]+)\.psd"', body) or
                 re.search(r'\n\t\tm_strAbilityImage = panorama:"file://\{images\}/([a-z0-9_./-]+)\.psd"', body))
        if found:
            images[key] = found[1]
    icons = {}
    for key, name in re.findall(r'^\s*"([a-z0-9_]+)"\s+"((?:[^"\\]|\\.)*)"', names_text, re.M):
        name = name.replace('\\"', '"').strip()
        if key in images and name:
            icons.setdefault(name, images[key])
    if len(images) < 150 or "Spirit Shredder" not in icons or "Lucky Shot" not in icons:
        raise SystemExit(f"item icon table looks wrong ({len(images)} items, {len(icons)} names)")
    rows = ",\n".join(f"  {json.dumps(name, ensure_ascii=False)}: {json.dumps(path)}" for name, path in sorted(icons.items()))
    return ("// Generated by observer_hud/scripts/refresh-stock.py from GameTracking abilities.vdata and\n"
            "// citadel_gc_mod_names_english.txt. English shop name -> icon under file://{images}/ (.psd omitted). Do not edit.\n"
            f"var OH_ITEM_ICONS = {{\n{rows}\n}};\n")


def main():
    args = set(sys.argv[1:])
    check, accept = "--check" in args, "--accept" in args
    head = json.loads(dlf.fetch(f"https://api.github.com/repos/{REPO}/commits/master"))
    commit = head["sha"]
    pin = json.loads(PIN.read_text(encoding="utf-8")) if PIN.exists() else {"files": {}}
    files = dict(pin["files"])
    pending = []

    print(f"GameTracking master {commit[:10]} ({head['commit']['message'].split('|')[0].strip()})")
    for stock, local in {**STOCK, **OVERRIDDEN}.items():
        data = dlf.fetch(f"https://raw.githubusercontent.com/{REPO}/{commit}/{stock}")
        digest = hashlib.sha256(data).hexdigest()
        if files.get(stock) == digest and (stock not in STOCK or (MODULE / local).exists()):
            continue
        if stock in STOCK:
            print(f"  {'stale' if check else 'refreshed'}: observer_hud/{local}")
            if check:
                pending.append(stock)
            else:
                (MODULE / local).parent.mkdir(parents=True, exist_ok=True)
                (MODULE / local).write_bytes(data)
                files[stock] = digest
        elif accept and not check:
            print(f"  accepted rebase: observer_hud/{local}")
            files[stock] = digest
        else:
            print(f"  REBASE NEEDED: {stock} changed upstream -> port into observer_hud/{local}")
            pending.append(stock)

    for sources, out, build in ((dlf.HERO_SOURCES, HEROES_OUT, hero_table), (dlf.ICON_SOURCES, ICONS_OUT, icon_table),
                                (dlf.MOD_ICON_SOURCES, ITEMS_OUT, item_table)):
        data = [dlf.fetch(f"https://raw.githubusercontent.com/{REPO}/{commit}/{path}") for path in sources]
        digests = [hashlib.sha256(item).hexdigest() for item in data]
        if all(pin["files"].get(path) == digest for path, digest in zip(sources, digests)) and (MODULE / out).exists():
            continue
        print(f"  {'stale' if check else 'regenerated'}: observer_hud/{out}")
        if check:
            pending.append(out)
        else:
            (MODULE / out).parent.mkdir(parents=True, exist_ok=True)
            (MODULE / out).write_text(build(*(item.decode("utf-8") for item in data)), encoding="utf-8", newline="\n")
            files.update(zip(sources, digests))
    if not check:
        PIN.write_text(json.dumps({"repo": REPO, "commit": commit, "files": files}, indent=2) + "\n", encoding="utf-8")
    if not pending:
        print("  pinned stock files are current")
    sys.exit(1 if pending else 0)


if __name__ == "__main__":
    main()
